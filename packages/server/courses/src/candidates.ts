/**
 * Bounded target-distance candidate search (M2-01i).
 *
 * WHAT THIS IS, AND WHAT IT IS NOT.
 *
 * A target distance is an approximation. This module generates a small, bounded number of
 * **proposals** for one: it picks loop shapes from a recorded seed, asks our own pedestrian
 * engine to route each of them, measures what came back and offers only the ones that are
 * close enough to be worth looking at. Nothing it produces is saved, approved, or a course.
 * The owner picks one, and only that pick writes anything.
 *
 * WHY IT COMPOSES ROUTED LEGS INSTEAD OF CALLING THE ENGINE'S ROUND TRIP.
 *
 * GraphHopper does have `algorithm=round_trip` (M2-01d measured it: 4,428.763 m for a
 * 5,000 m target). It is not used here, and the reason is a guard rather than a preference.
 * M2-01g refuses any engine answer that does not attest the graph edges behind it, that
 * does not start at the first snapped waypoint, end at the last and visit the rest **in the
 * requested order**. A round trip's waypoints are generated by the engine, so that order
 * check has nothing to check against and would have to be relaxed — which would weaken the
 * exact defence that keeps a fallback straight line from being reported as success. Instead
 * every candidate here is built from waypoints WE chose, routed through the ordinary
 * bounded path, and therefore every leg of every candidate has already passed that guard
 * unchanged. The plan allows either the engine's round trip or our own bounded search; this
 * is the second, and it costs nothing in safety.
 *
 * EVERYTHING IS BOUNDED AND RECORDED. Candidates, attempts, wall-clock time and the
 * geographic radius all have ceilings ({@link targetDistanceLimits}), the seed of the search
 * and of each attempt is recorded so the same search can be run again, and the evaluation
 * version travels with every candidate. The attempt log keeps the rejected attempts too: a
 * reader has to be able to see that eight computations produced two candidates.
 *
 * NOTHING HERE JUDGES PASSABILITY. The engine answering means a graph had edges. It is not
 * evidence about stairs, surface, opening hours or access restrictions — we have no such
 * data in this build, and {@link CourseCandidateEvaluation}'s `knowledge` says `unknown`
 * for each of them rather than treating a missing fact as satisfied.
 */
export class CandidateSearchError extends Error {
  constructor(
    readonly code:
      | 'CANDIDATE_TOO_MANY_LOCKED_WAYPOINTS'
      | 'CANDIDATE_LOCKED_WAYPOINTS_EXCEED_TARGET'
      | 'CANDIDATE_LOCKED_WAYPOINT_OUTSIDE_SEARCH_AREA'
      | 'CANDIDATE_LOCKED_FINISH_NOT_A_LOOP'
      | 'CANDIDATE_WAYPOINT_COUNT_MISMATCH'
      | 'CANDIDATE_START_MISSING'
      | 'CANDIDATE_TARGET_OUT_OF_RANGE',
  ) {
    super(code);
    this.name = 'CandidateSearchError';
  }
}

/**
 * The first radius to try, as a share of the distance still to cover.
 *
 * A candidate is a triangle whose first vertex is the origin and whose other two sit at
 * one radius from it, 120 degrees apart: the straight-line perimeter is therefore
 * `r + 2r·sin(60°) + r = (2 + √3)·r`. Starting from that share puts the first attempt near
 * the target before the search has measured anything; every later attempt is steered by
 * what the engine actually answered, because a walked route is longer than its chords.
 */
const TRIANGLE_RADIUS_RATIO = 1 / (2 + Math.sqrt(3));
/** Generated points per attempt, on top of the origin and any locked waypoints. */
const GENERATED_POINTS = 2;
/** Repeated share at or above which a loop is reported as an out-and-back. */
const OUT_AND_BACK_RATIO = 0.4;
/** A failure that says the engine or the tenant bound stopped us, not this shape. */
const TERMINAL_OUTCOMES = new Set([
  'cancelled',
  'overloaded',
  'timeout',
  'engine_unavailable',
  'graph_mismatch',
]);

export type CandidateRouteOutcome =
  | 'no_route'
  | 'outside_coverage'
  | 'snap_too_far'
  | 'timeout'
  | 'cancelled'
  | 'overloaded'
  | 'compute_budget_exceeded'
  | 'engine_unavailable'
  | 'engine_contract_violation'
  | 'graph_mismatch'
  | 'request_refused';

export interface CandidateSnappedWaypoint {
  readonly requested: RoutingPosition;
  readonly snapped: RoutingPosition;
  readonly snapDistanceMeters: number;
}

export type CandidateRouteAnswer =
  | {
      readonly kind: 'computed';
      readonly coordinates: readonly CoursePosition[];
      readonly distanceMeters: number;
      readonly durationSeconds: number;
      readonly snappedWaypoints: readonly CandidateSnappedWaypoint[];
      readonly computation: RouteComputationRecord;
    }
  | {
      readonly kind: 'refused';
      readonly outcome: CandidateRouteOutcome;
      /** `null` when the engine was never reached, which is a different fact. */
      readonly computation: RouteComputationRecord | null;
    };

/**
 * The one way this search reaches the engine. It is the ordinary bounded walking-route
 * path — the same admission control, the same deadline, the same answer validation — so
 * this module cannot route around any of it.
 */
export interface CandidateLegRouter {
  route(
    input: {
      readonly requestId: string;
      readonly requestRevision: number;
      readonly waypoints: readonly CoursePosition[];
    },
    /**
     * Aborted when the whole search runs out of budget or the caller goes away. Honouring
     * it is what makes the search budget a bound on the search rather than a bound on the
     * gaps between its calls.
     */
    context: { readonly signal: AbortSignal },
  ): Promise<CandidateRouteAnswer>;
}

/**
 * How the search arms its own deadline. Injected so a test can fire it against a fake
 * clock instead of waiting: a budget that only real time can enforce is a budget no test
 * can hold in place.
 */
export interface CandidateDeadlineScheduler {
  schedule(onDeadline: () => void, delayMilliseconds: number): () => void;
}

const realDeadlineScheduler: CandidateDeadlineScheduler = {
  schedule(onDeadline, delayMilliseconds) {
    const timer = setTimeout(onDeadline, Math.max(0, delayMilliseconds));
    return () => clearTimeout(timer);
  },
};

export interface CandidateSearchClock {
  now(): Date;
}

