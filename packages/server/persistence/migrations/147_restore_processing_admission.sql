-- 7. (A) Census window.
CREATE FUNCTION public.open_restore_processing_admission_window(expected_revision bigint,
 target_nonce uuid,target_incarnation uuid) RETURNS jsonb
 LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE r public.restore_processing_admission%ROWTYPE; x record; n integer:=0;
BEGIN
 IF NOT public.restore_processing_plain_owner()
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_OWNER_REQUIRED' USING ERRCODE='42501'; END IF;
 IF expected_revision IS NULL OR expected_revision<1 OR target_nonce IS NULL OR target_incarnation IS NULL
 THEN RAISE EXCEPTION 'INVALID_RESTORE_PROCESSING_ADMIT'; END IF;
 -- Statement snapshots under READ COMMITTED are taken after the locks below.
 IF current_setting('transaction_isolation')<>'read committed'
  OR current_setting('session_replication_role')<>'origin'
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ADMIT_CONTEXT'; END IF;
 PERFORM pg_advisory_xact_lock(77210,1);
 SELECT * INTO r FROM public.restore_processing_admission WHERE singleton FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CONTROL_MISSING'; END IF;
 -- D4: a NULL target never matches; the bound target came from an exact close at this revision.
 IF r.state<>'CLOSED' OR r.local_revision IS DISTINCT FROM expected_revision
  OR r.target_nonce IS DISTINCT FROM $2 OR r.target_incarnation IS DISTINCT FROM $3
  OR r.generation_id IS DISTINCT FROM public.current_restore_generation()
  OR NOT EXISTS(SELECT 1 FROM public.restore_processing_close_receipt q
   WHERE q.result_revision=$1 AND q.target_nonce=$2 AND q.target_incarnation=$3
    AND q.generation_id=r.generation_id)
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CONTROL_CONFLICT'; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgname='restore_processing_force_rls_at_commit'
   AND tgrelid='public.restore_processing_admission'::regclass AND tgenabled='O')
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ADMIT_CONTEXT'; END IF;
 IF public.restore_processing_admission_roster_drift()
  OR EXISTS(SELECT 1 FROM public.restore_processing_admission_roster() ro
   JOIN pg_class c ON c.oid=to_regclass(format('%I.%I',ro.schema_name,ro.relation_name))
   WHERE c.relforcerowsecurity<>ro.force_rls)
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ROSTER_MISMATCH'; END IF;
 -- Lock every census relation (retained + authentication_reset) in C order, then open RLS
 -- visibility for the owner only. The runtime role is not the owner, so its RLS is unaffected.
 FOR x IN SELECT * FROM public.restore_processing_admission_roster()
   WHERE relation_class IN ('retained','authentication_reset')
   ORDER BY schema_name COLLATE "C",relation_name COLLATE "C" LOOP
  EXECUTE format('LOCK TABLE %I.%I IN ACCESS EXCLUSIVE MODE',x.schema_name,x.relation_name);
  IF x.force_rls THEN
   EXECUTE format('ALTER TABLE %I.%I NO FORCE ROW LEVEL SECURITY',x.schema_name,x.relation_name);
  END IF;
  n:=n+1;
 END LOOP;
 -- Arm the deferred commit guard (no semantic change to the row).
 UPDATE public.restore_processing_admission SET local_revision=local_revision WHERE singleton;
 RETURN jsonb_build_object('xid',txid_current()::text,'censusRelations',n,
  'rosterSha256',public.restore_processing_admission_roster_sha256());
END $$;
REVOKE ALL ON FUNCTION public.open_restore_processing_admission_window(bigint,uuid,uuid) FROM PUBLIC;

-- 8. (C) Atomic admission.
-- census: exactly the retained + authentication_reset relations, strictly ordered by
-- (schema, relation) COLLATE "C", each {"schema","relation","rowCount"}; rowCount is the
-- AUTHENTICATED expected post-tail count computed in TS; authentication_reset rows must be 0.
-- census_sha256 = sha256('wm-restore-admission-census-v1\n' || join('\n', schema.relation=rowCount)).
CREATE FUNCTION public.admit_restore_processing_exact(expected_revision bigint,command_id uuid,
 target_nonce uuid,target_incarnation uuid,artifact_sha256 text,head_sha256 text,
 postconditions_sha256 text,census jsonb,census_sha256 text,observed_xid bigint) RETURNS jsonb
 LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE r public.restore_processing_admission%ROWTYPE; prior public.restore_processing_admit_receipt%ROWTYPE;
 item jsonb; x record; ps text; pr text; s text; rel text; wanted bigint; actual bigint; lines text[]:='{}';
 roster_digest text; computed text; required integer;
BEGIN
 IF NOT public.restore_processing_plain_owner()
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_OWNER_REQUIRED' USING ERRCODE='42501'; END IF;
 IF command_id IS NULL OR expected_revision IS NULL OR expected_revision<1
  OR target_nonce IS NULL OR target_incarnation IS NULL OR observed_xid IS NULL
  OR artifact_sha256 IS NULL OR artifact_sha256 !~ '^[a-f0-9]{64}$'
  OR head_sha256 IS NULL OR head_sha256 !~ '^[a-f0-9]{64}$'
  OR postconditions_sha256 IS NULL OR postconditions_sha256 !~ '^[a-f0-9]{64}$'
  OR census_sha256 IS NULL OR census_sha256 !~ '^[a-f0-9]{64}$'
  OR census IS NULL OR jsonb_typeof(census)<>'array' OR jsonb_array_length(census) NOT BETWEEN 1 AND 1000
 THEN RAISE EXCEPTION 'INVALID_RESTORE_PROCESSING_ADMIT'; END IF;
 PERFORM pg_advisory_xact_lock(77210,1);
 SELECT * INTO r FROM public.restore_processing_admission WHERE singleton FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CONTROL_MISSING'; END IF;
 -- Replay is receipt-derived and only while that admission is still the current state.
 SELECT * INTO prior FROM public.restore_processing_admit_receipt q WHERE q.command_id=$2;
 IF FOUND THEN
  IF prior.expected_revision IS DISTINCT FROM $1 OR prior.target_nonce IS DISTINCT FROM $3
   OR prior.target_incarnation IS DISTINCT FROM $4 OR prior.artifact_sha256 IS DISTINCT FROM $5
   OR prior.head_sha256 IS DISTINCT FROM $6 OR prior.postconditions_sha256 IS DISTINCT FROM $7
   OR prior.census IS DISTINCT FROM $8 OR prior.census_sha256 IS DISTINCT FROM $9
  THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ADMIT_CONFLICT'; END IF;
  IF r.state<>'ADMITTED' OR r.local_revision IS DISTINCT FROM prior.result_revision
  THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ADMIT_SUPERSEDED'; END IF;
  RETURN jsonb_build_object('replayed',true,'resultRevision',prior.result_revision::text,
   'rosterSha256',prior.roster_sha256,'censusSha256',prior.census_sha256,
   'control',public.read_restore_processing_admission());
 END IF;
 IF EXISTS(SELECT 1 FROM public.restore_processing_close_receipt q WHERE q.command_id=$2)
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_COMMAND_ID_REUSED'; END IF;
 IF r.state<>'CLOSED' OR r.local_revision IS DISTINCT FROM expected_revision
  OR r.target_nonce IS DISTINCT FROM $3 OR r.target_incarnation IS DISTINCT FROM $4
  OR r.generation_id IS DISTINCT FROM public.current_restore_generation()
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CONTROL_CONFLICT'; END IF;
 IF r.local_revision=9223372036854775807 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_REVISION_EXHAUSTED'; END IF;
 -- Same transaction as (A) and the observation. A window can only be open (census relation
 -- NO FORCE + ACCESS EXCLUSIVE by this backend) inside the transaction that opened it, because
 -- the deferred guard makes such a state uncommittable.
 IF observed_xid IS DISTINCT FROM txid_current()
  OR current_setting('transaction_isolation')<>'read committed'
  OR current_setting('session_replication_role')<>'origin'
  OR NOT EXISTS(SELECT 1 FROM pg_trigger WHERE tgname='restore_processing_force_rls_at_commit'
   AND tgrelid='public.restore_processing_admission'::regclass AND tgenabled='O')
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ADMIT_CONTEXT'; END IF;
 IF EXISTS(SELECT 1 FROM public.restore_processing_admission_roster() ro
   LEFT JOIN pg_class c ON c.oid=to_regclass(format('%I.%I',ro.schema_name,ro.relation_name))
   WHERE ro.relation_class IN ('retained','authentication_reset') AND (c.oid IS NULL
    OR c.relforcerowsecurity
    OR NOT EXISTS(SELECT 1 FROM pg_locks l WHERE l.locktype='relation' AND l.pid=pg_backend_pid()
     AND l.database=(SELECT oid FROM pg_database WHERE datname=current_database())
     AND l.relation=c.oid AND l.mode='AccessExclusiveLock' AND l.granted)))
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_WINDOW_NOT_OPEN'; END IF;
 -- D5 and completeness are re-decided at admission time (objects created after open_).
 IF public.restore_processing_admission_roster_drift()
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ROSTER_MISMATCH'; END IF;
 -- Census shape, C order, completeness, then the whole-table recount.
 FOR item IN SELECT value FROM jsonb_array_elements(census) LOOP
  IF jsonb_typeof(item)<>'object'
   OR (SELECT array_agg(k ORDER BY k COLLATE "C") FROM jsonb_object_keys(item) k)
      IS DISTINCT FROM ARRAY['relation','rowCount','schema']::text[]
   OR jsonb_typeof(item->'schema')<>'string' OR jsonb_typeof(item->'relation')<>'string'
   OR jsonb_typeof(item->'rowCount')<>'number'
   OR (item->>'rowCount') !~ '^(0|[1-9][0-9]{0,15})$'
  THEN RAISE EXCEPTION 'INVALID_RESTORE_PROCESSING_ADMIT'; END IF;
  s:=item->>'schema'; rel:=item->>'relation'; wanted:=(item->>'rowCount')::bigint;
  IF wanted>9007199254740991
   OR (ps IS NOT NULL AND (s COLLATE "C",rel COLLATE "C")<=(ps COLLATE "C",pr COLLATE "C"))
  THEN RAISE EXCEPTION 'INVALID_RESTORE_PROCESSING_ADMIT'; END IF;
  ps:=s; pr:=rel;
  SELECT * INTO x FROM public.restore_processing_admission_roster() q
   WHERE q.schema_name=s AND q.relation_name=rel AND q.relation_class IN ('retained','authentication_reset');
  IF NOT FOUND THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ROSTER_MISMATCH'; END IF;
  -- Provider tokens, sessions and login state never come back live (artifact: explicit_empty).
  IF x.relation_class='authentication_reset' AND wanted<>0
  THEN RAISE EXCEPTION 'RESTORE_PROCESSING_POSTCONDITION_FAILED'; END IF;
  EXECUTE format('SELECT count(*) FROM %I.%I',s,rel) INTO actual;
  IF actual IS DISTINCT FROM wanted THEN RAISE EXCEPTION 'RESTORE_PROCESSING_POSTCONDITION_FAILED'; END IF;
  lines:=lines||(s||'.'||rel||'='||wanted::text);
 END LOOP;
 SELECT count(*) INTO required FROM public.restore_processing_admission_roster()
  WHERE relation_class IN ('retained','authentication_reset');
 IF cardinality(lines)<>required THEN RAISE EXCEPTION 'RESTORE_PROCESSING_ROSTER_MISMATCH'; END IF;
 computed:=encode(sha256(convert_to('wm-restore-admission-census-v1'||E'\n'||array_to_string(lines,E'\n'),'UTF8')),'hex');
 IF computed IS DISTINCT FROM census_sha256 THEN RAISE EXCEPTION 'INVALID_RESTORE_PROCESSING_ADMIT'; END IF;
 -- Close the window: re-FORCE exactly the pinned relations and prove every roster flag.
 FOR x IN SELECT * FROM public.restore_processing_admission_roster()
   WHERE relation_class IN ('retained','authentication_reset') AND force_rls
   ORDER BY schema_name COLLATE "C",relation_name COLLATE "C" LOOP
  EXECUTE format('ALTER TABLE %I.%I FORCE ROW LEVEL SECURITY',x.schema_name,x.relation_name);
 END LOOP;
 IF EXISTS(SELECT 1 FROM public.restore_processing_admission_roster() ro
   LEFT JOIN pg_class c ON c.oid=to_regclass(format('%I.%I',ro.schema_name,ro.relation_name))
   WHERE c.oid IS NULL OR c.relrowsecurity<>ro.force_rls OR c.relforcerowsecurity<>ro.force_rls)
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_POSTCONDITION_FAILED'; END IF;
 roster_digest:=public.restore_processing_admission_roster_sha256();
 UPDATE public.restore_processing_admission SET state='ADMITTED',local_revision=r.local_revision+1,
  admitted_artifact_sha256=$5,admitted_head_sha256=$6,admitted_postconditions_sha256=$7
  WHERE singleton RETURNING * INTO r;
 INSERT INTO public.restore_processing_admit_receipt
  VALUES($2,$1,r.local_revision,r.generation_id,$3,$4,$5,$6,$7,roster_digest,$9,$8);
 RETURN jsonb_build_object('replayed',false,'resultRevision',r.local_revision::text,
  'rosterSha256',roster_digest,'censusSha256',$9,'control',public.read_restore_processing_admission());
END $$;
REVOKE ALL ON FUNCTION public.admit_restore_processing_exact(bigint,uuid,uuid,uuid,text,text,text,jsonb,text,bigint) FROM PUBLIC;

-- 9. close_: SQL101 body + (a) cross-table command_id check after the replay lookup,
-- (b) the SET list gains state='CLOSED' and clears admitted_* (ADMITTED -> CLOSED). It keeps the
-- SQL101 session_user-only owner check on purpose (closing is the fail-safe direction).
CREATE OR REPLACE FUNCTION public.close_restore_processing_exact(expected_revision bigint,command_id uuid,
 target_nonce uuid DEFAULT NULL,target_incarnation uuid DEFAULT NULL) RETURNS jsonb
 LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path=pg_catalog,pg_temp AS $$
DECLARE r public.restore_processing_admission%ROWTYPE; prior public.restore_processing_close_receipt%ROWTYPE;
BEGIN
 IF session_user<>pg_get_userbyid((SELECT relowner FROM pg_class WHERE oid='public.restore_processing_admission'::regclass))
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_OWNER_REQUIRED' USING ERRCODE='42501'; END IF;
 IF command_id IS NULL OR expected_revision IS NULL OR expected_revision<1
  OR (target_nonce IS NULL)<>(target_incarnation IS NULL)
 THEN RAISE EXCEPTION 'INVALID_RESTORE_PROCESSING_CLOSE'; END IF;
 PERFORM pg_advisory_xact_lock(77210,1);
 SELECT * INTO r FROM public.restore_processing_admission WHERE singleton FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CONTROL_MISSING'; END IF;
 SELECT * INTO prior FROM public.restore_processing_close_receipt q WHERE q.command_id=$2;
 IF FOUND THEN
  IF prior.expected_revision IS DISTINCT FROM $1 OR prior.target_nonce IS DISTINCT FROM $3
   OR prior.target_incarnation IS DISTINCT FROM $4
  THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CLOSE_CONFLICT'; END IF;
  RETURN jsonb_build_object('state','CLOSED','localRevision',prior.result_revision::text,
   'generationId',prior.generation_id,'targetNonce',prior.target_nonce,'targetIncarnation',prior.target_incarnation,
   'admissionAllowed',false,'targetAttested',false);
 END IF;
 IF EXISTS(SELECT 1 FROM public.restore_processing_admit_receipt q WHERE q.command_id=$2)
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CLOSE_CONFLICT'; END IF;
 IF r.local_revision IS DISTINCT FROM expected_revision THEN RAISE EXCEPTION 'RESTORE_PROCESSING_CONTROL_CONFLICT'; END IF;
 IF r.local_revision=9223372036854775807 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_REVISION_EXHAUSTED'; END IF;
 UPDATE public.restore_processing_admission SET state='CLOSED',local_revision=r.local_revision+1,
  generation_id=public.current_restore_generation(),target_nonce=$3,target_incarnation=$4,
  admitted_artifact_sha256=NULL,admitted_head_sha256=NULL,admitted_postconditions_sha256=NULL WHERE singleton
  RETURNING * INTO r;
 INSERT INTO public.restore_processing_close_receipt VALUES($2,$1,r.local_revision,r.generation_id,$3,$4);
 RETURN public.read_restore_processing_admission();
END $$;
REVOKE ALL ON FUNCTION public.close_restore_processing_exact(bigint,uuid,uuid,uuid) FROM PUBLIC;
