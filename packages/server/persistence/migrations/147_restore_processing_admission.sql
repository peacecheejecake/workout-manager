-- EXT-RESTOREa atomic restore processing admission (profile27 / runtime-installation v11 extension).
-- Source: EXT-RESTOREa admission DDL proposal v2 (2026-10-13) with user decisions D1-D7 (2026-10-13):
--  D1 the SQL101 CLOSED guard is strengthened here (assert_restore_processing_closed also requires
--     state='CLOSED'); read_/require_/close_ are redefined in place, nothing is loosened.
--  D2/D3 an ADMITTED current-generation target passes require_restore_processing_admission() for
--     the 103 reserve/dispatch and 106 store/source-ref callers (each keeps its own later gates);
--     104 assert_ai_settings_write_target() is unchanged, so AI-settings writes stay blocked
--     while a restore target is bound (CLOSED or ADMITTED).
--  D4 a never-restored database (NULL target) can never be ADMITTED.
--  D5 the restore-only loader namespaces (117/119/125) must be absent before a window opens and
--     when admission is decided.
--  D6 fail-closed census source (TS): artifacts with tail segments are not admitted until the
--     tail replay exposes authenticated per-relation deltas.
--  D7 this DDL is a profile27 extension; profile26 (installation v10) bytes are untouched.
-- This migration supersedes the "CURRENT101: ALWAYS DENY" comment in 106 (line 433) without
-- editing 106: the deny is now conditional on an ADMITTED current-generation control row.
--
-- Threat model: the plain owner is a trusted but possibly buggy host. SQL makes admission atomic,
-- complete and current; it does not defend against a malicious owner (who could DROP/ALTER its
-- own objects). The runtime role never gets EXECUTE on open_/admit_/close_/assert_ or the roster.
--
-- Protocol (one READ COMMITTED transaction, plain owner, no superuser/BYPASSRLS):
--   BEGIN ISOLATION LEVEL READ COMMITTED;
--   SELECT public.open_restore_processing_admission_window(rev, nonce, incarnation);   -- (A)
--     exclusive (77210,1); CLOSED + bound target + exact close receipt; roster complete; no loader
--     namespace; ACCESS EXCLUSIVE on every census relation in C order; NO FORCE RLS on the forced
--     census relations (owner-only visibility); arms a deferred commit guard.
--   host observes digests/counts/sequences/objects/tail as owner (sees every tenant)       -- (B)
--   SELECT public.admit_restore_processing_exact(..., census, census_sha256, observed_xid); -- (C)
--     proves (A) in this transaction, whole-table recount == authenticated census, the
--     authentication_reset relations are empty, re-FORCE, ADMITTED, immutable receipt.
--   COMMIT;  -- the deferred guard rejects any commit that leaves a census relation NO FORCE.
-- Any failure or ROLLBACK (incl. ROLLBACK TO SAVEPOINT) reverts the NO FORCE catalog change.
--
-- The roster literal below is GENERATED by scripts/generate-restore-admission-roster.mts from the
-- pinned native-catalog roster (e13dc970...0619) plus the successor relation list
-- (src/full-restore-admission-roster-v1/successor-relations.json) and the live catalog of a clean
-- install. It must be regenerated whenever a later DDL adds a relation (an unregistered relation
-- blocks admission by design).

-- 1. Control row: ADMITTED state and admitted_* binding.
ALTER TABLE public.restore_processing_admission
 DROP CONSTRAINT restore_processing_admission_state_check;
ALTER TABLE public.restore_processing_admission
 ADD CONSTRAINT restore_processing_admission_state_check CHECK(state IN ('CLOSED','ADMITTED')),
 ADD COLUMN admitted_artifact_sha256 text CHECK(admitted_artifact_sha256 ~ '^[a-f0-9]{64}$'),
 ADD COLUMN admitted_head_sha256 text CHECK(admitted_head_sha256 ~ '^[a-f0-9]{64}$'),
 ADD COLUMN admitted_postconditions_sha256 text CHECK(admitted_postconditions_sha256 ~ '^[a-f0-9]{64}$'),
 ADD CONSTRAINT restore_processing_admitted_shape CHECK(
  (state='CLOSED' AND admitted_artifact_sha256 IS NULL AND admitted_head_sha256 IS NULL
    AND admitted_postconditions_sha256 IS NULL)
  OR (state='ADMITTED' AND target_nonce IS NOT NULL AND target_incarnation IS NOT NULL
    AND admitted_artifact_sha256 IS NOT NULL AND admitted_head_sha256 IS NOT NULL
    AND admitted_postconditions_sha256 IS NOT NULL));

