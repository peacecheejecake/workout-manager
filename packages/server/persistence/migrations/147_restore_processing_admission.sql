-- Fail-closed plain-owner predicate (NULL -> not plain).
CREATE FUNCTION public.restore_processing_plain_owner() RETURNS boolean
 LANGUAGE sql STABLE SET search_path=pg_catalog,pg_temp AS $$
 SELECT coalesce((SELECT session_user=o AND current_user=o AND NOT r.rolsuper AND NOT r.rolbypassrls
   FROM pg_roles r,
    (SELECT pg_get_userbyid(relowner)::name o FROM pg_class WHERE oid='public.restore_processing_admission'::regclass) w
   WHERE r.rolname=session_user),false)
$$;
REVOKE ALL ON FUNCTION public.restore_processing_plain_owner() FROM PUBLIC;

-- Completeness (true = drift): a loader namespace exists; a roster relation is missing, not an
-- owned permanent non-partition plain table, or has the wrong relrowsecurity; or a relation of
-- kind r/p/f/m exists outside pg_* / information_schema without a roster row. FORCE flags are
-- checked by the callers because the census window changes them.
CREATE FUNCTION public.restore_processing_admission_roster_drift() RETURNS boolean
 LANGUAGE sql STABLE SET search_path=pg_catalog,pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname=ANY(public.restore_processing_admission_loader_namespaces()))
  OR EXISTS(SELECT 1 FROM public.restore_processing_admission_roster() ro
   LEFT JOIN pg_class c ON c.oid=to_regclass(format('%I.%I',ro.schema_name,ro.relation_name))
   WHERE c.oid IS NULL OR c.relkind<>'r' OR c.relispartition OR c.relpersistence<>'p'
    OR c.relowner<>(SELECT relowner FROM pg_class WHERE oid='public.restore_processing_admission'::regclass)
    OR c.relrowsecurity<>ro.force_rls)
  OR EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace s ON s.oid=c.relnamespace
   WHERE c.relkind IN ('r','p','f','m') AND s.nspname !~ '^pg_' AND s.nspname<>'information_schema'
    AND NOT EXISTS(SELECT 1 FROM public.restore_processing_admission_roster() rx
     WHERE rx.schema_name=s.nspname AND rx.relation_name=c.relname))
$$;
REVOKE ALL ON FUNCTION public.restore_processing_admission_roster_drift() FROM PUBLIC;

-- 4. Commit guard: a forced roster relation can never be committed with RLS/FORCE RLS off.
-- Deferred constraint trigger on the control row; every open/admit/close UPDATE arms it.
-- SET CONSTRAINTS ... IMMEDIATE only makes it fire earlier (fail closed). Disabling triggers needs
-- session_replication_role (superuser/granted) or owner DDL; open_/admit_ check both.
CREATE FUNCTION public.guard_restore_processing_force_rls() RETURNS trigger
 LANGUAGE plpgsql SET search_path=pg_catalog,pg_temp AS $$ BEGIN
