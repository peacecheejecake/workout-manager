-- Canonical roster digest; TS pins the same value (RESTORE_ADMISSION_ROSTER_SHA256). PG text has
-- no NUL, so the domain separator is a newline.
CREATE FUNCTION public.restore_processing_admission_roster_sha256() RETURNS text
 LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path=pg_catalog,pg_temp AS $$
 SELECT encode(sha256(convert_to('wm-restore-admission-roster-v1'||E'\n'||
  string_agg(schema_name||'.'||relation_name||'|'||relation_class||'|'||force_rls::text,E'\n'
   ORDER BY schema_name COLLATE "C",relation_name COLLATE "C"),'UTF8')),'hex')
 FROM public.restore_processing_admission_roster()
$$;
REVOKE ALL ON FUNCTION public.restore_processing_admission_roster_sha256() FROM PUBLIC;

