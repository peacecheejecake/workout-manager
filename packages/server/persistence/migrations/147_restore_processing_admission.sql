   LEFT JOIN pg_class c ON c.oid=to_regclass(format('%I.%I',ro.schema_name,ro.relation_name))
   WHERE ro.force_rls AND (c.oid IS NULL OR NOT c.relrowsecurity OR NOT c.relforcerowsecurity))
 THEN RAISE EXCEPTION 'RESTORE_PROCESSING_WINDOW_OPEN_AT_COMMIT'; END IF;
 RETURN NULL; END $$;
REVOKE ALL ON FUNCTION public.guard_restore_processing_force_rls() FROM PUBLIC;
CREATE CONSTRAINT TRIGGER restore_processing_force_rls_at_commit
 AFTER UPDATE ON public.restore_processing_admission DEFERRABLE INITIALLY DEFERRED
 FOR EACH ROW EXECUTE FUNCTION public.guard_restore_processing_force_rls();

