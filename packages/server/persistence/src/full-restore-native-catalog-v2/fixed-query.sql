collations AS MATERIALIZED (SELECT DISTINCT v FROM expanded e CROSS JOIN LATERAL jsonb_path_query(e.catalog,'$.relations[*].columns[*].collation') v WHERE v<>'null'::jsonb UNION SELECT DISTINCT v FROM expanded e CROSS JOIN LATERAL jsonb_path_query(e.catalog,'$.relations[*].primaryKey.components[*].collation') v WHERE v<>'null'::jsonb),
routines AS MATERIALIZED (
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.send') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.input') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.output') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.elementType.send') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.elementType.input') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.elementType.output') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM types t CROSS JOIN LATERAL jsonb_path_query(t.v,'$.casts[*].function') AS child(value) WHERE child.value<>'null'::jsonb UNION
 SELECT DISTINCT child.value AS v FROM classes o CROSS JOIN LATERAL jsonb_path_query(o.v,'$.operators[*].function') AS child(value) UNION
 SELECT DISTINCT child.value AS v FROM classes o CROSS JOIN LATERAL jsonb_path_query(o.v,'$.supportProcedures[*].function') AS child(value)
), normalized_types AS MATERIALIZED (SELECT (v-ARRAY['send','input','output','elementType','casts'])||jsonb_build_object(
 'sendRoutineOid',v#>'{send,oid}','inputRoutineOid',v#>'{input,oid}','outputRoutineOid',v#>'{output,oid}',
 'elementType',CASE WHEN v->'elementType'='null'::jsonb THEN 'null'::jsonb ELSE ((v->'elementType')-ARRAY['send','input','output'])||jsonb_build_object('sendRoutineOid',v#>'{elementType,send,oid}','inputRoutineOid',v#>'{elementType,input,oid}','outputRoutineOid',v#>'{elementType,output,oid}') END,
 'casts',COALESCE((SELECT jsonb_agg((c.value-'function')||jsonb_build_object('functionRoutineOid',c.value#>'{function,oid}') ORDER BY c.ord) FROM jsonb_array_elements(v->'casts') WITH ORDINALITY c(value,ord)),'[]'::jsonb)) AS v FROM types),
normalized_classes AS MATERIALIZED (SELECT (v-ARRAY['operators','supportProcedures'])||jsonb_build_object(
 'operators',(SELECT jsonb_agg((c.value-'function')||jsonb_build_object('functionRoutineOid',c.value#>'{function,oid}') ORDER BY c.ord) FROM jsonb_array_elements(v->'operators') WITH ORDINALITY c(value,ord)),
 'supportProcedures',(SELECT jsonb_agg((c.value-'function')||jsonb_build_object('functionRoutineOid',c.value#>'{function,oid}') ORDER BY c.ord) FROM jsonb_array_elements(v->'supportProcedures') WITH ORDINALITY c(value,ord))) AS v FROM classes),
normalized AS MATERIALIZED (SELECT (e.catalog-ARRAY['schemaVersion','relations'])||jsonb_build_object('schemaVersion',2,'payloadEncoding','oid-normalized-native-catalog-v2',
 'relations',(SELECT jsonb_agg((r.value-ARRAY['columns','primaryKey'])||jsonb_build_object(
  'columns',(SELECT jsonb_agg((c.value-ARRAY['physicalType','collation'])||jsonb_build_object('physicalTypeOid',c.value#>'{physicalType,oid}','collationOid',c.value#>'{collation,oid}') ORDER BY c.ord) FROM jsonb_array_elements(r.value->'columns') WITH ORDINALITY c(value,ord)),
  'primaryKey',((r.value->'primaryKey')-'components')||jsonb_build_object('components',(SELECT jsonb_agg((c.value-ARRAY['opclass','collation'])||jsonb_build_object('opclassOid',c.value#>'{opclass,oid}','collationOid',c.value#>'{collation,oid}') ORDER BY c.ord) FROM jsonb_array_elements(r.value#>'{primaryKey,components}') WITH ORDINALITY c(value,ord)))) ORDER BY r.ord) FROM jsonb_array_elements(e.catalog->'relations') WITH ORDINALITY r(value,ord)),
 'pools',jsonb_build_object(
'physicalTypes',COALESCE((SELECT jsonb_agg(jsonb_build_object('oid',(v->>'oid')::bigint,'pgJsonbText',v::text,'metadataSha256',encode(sha256(convert_to(v::text,'UTF8')),'hex')) ORDER BY (v->>'oid')::bigint,v::text) FROM normalized_types),'[]'::jsonb),
'opclasses',COALESCE((SELECT jsonb_agg(jsonb_build_object('oid',(v->>'oid')::bigint,'pgJsonbText',v::text,'metadataSha256',encode(sha256(convert_to(v::text,'UTF8')),'hex')) ORDER BY (v->>'oid')::bigint,v::text) FROM normalized_classes),'[]'::jsonb),
'routines',COALESCE((SELECT jsonb_agg(jsonb_build_object('oid',(v->>'oid')::bigint,'pgJsonbText',v::text,'metadataSha256',encode(sha256(convert_to(v::text,'UTF8')),'hex')) ORDER BY (v->>'oid')::bigint,v::text) FROM routines),'[]'::jsonb),
'collations',COALESCE((SELECT jsonb_agg(jsonb_build_object('oid',(v->>'oid')::bigint,'pgJsonbText',v::text,'metadataSha256',encode(sha256(convert_to(v::text,'UTF8')),'hex')) ORDER BY (v->>'oid')::bigint,v::text) FROM collations),'[]'::jsonb)
 )) AS catalog FROM expanded e)
SELECT octet_length(catalog::text) AS catalog_bytes, CASE WHEN octet_length(catalog::text)<=8388608 THEN catalog ELSE NULL END AS catalog FROM normalized;
