/** Local structural parser. Array layout is provided by an independently read
 * same-snapshot SQL descriptor, NOT inferred or authenticated from JSON values. */
export function parseCurrentSourceExtraPhysicalRows(raw: unknown): CurrentSourceExtraPhysicalRow[] {
  plain(raw, CURRENT_SOURCE_PARTITION_TOTAL_BYTES);
  if (!Array.isArray(raw) || raw.length > 5000) reject('PHYSICAL_ROW_LIMIT');
  // Check finite SQL dimensions before invoking either recursive value codec.
  // Plain ingress already excludes getters/prototypes/cycles; this shallow view
  // does not grant authority or replace each relation's exact column schema.
  const layoutEntries = z
    .array(
      z.strictObject({
        ordinal: integer,
        relation: z.enum(currentSourceExtraRelations),
        row: z.record(z.string(), z.unknown()),
        arrayLayouts: z.record(z.string(), arrayLayout),
      }),
    )
    .max(5000)
    .safeParse(raw);
  if (!layoutEntries.success) reject();
  for (const entry of layoutEntries.data) {
    for (const name of currentSourceExtraPhysicalRoster[entry.relation].arrayColumns) {
      const layout = entry.arrayLayouts[name];
      if (!layout) reject('INVALID_ARRAY_LAYOUT');
      checkLayout(entry.row[name], layout);
    }
  }
  const result = z.array(entrySchema).max(5000).safeParse(raw);
  if (!result.success) reject();
  let previousRelation = -1,
    previousKey = '';
  const seen = new Set<string>();
  for (const [i, entry] of result.data.entries()) {
    plain(entry.row, CURRENT_SOURCE_PARTITION_ROW_BYTES);
    if (entry.ordinal !== i + 1) reject();
    const definition = currentSourceExtraPhysicalRoster[entry.relation];
    const fields = z.record(z.string(), z.unknown()).parse(entry.row);
    const layouts = z.record(z.string(), arrayLayout).parse(entry.arrayLayouts);
    for (const name of definition.arrayColumns) {
      const layout = layouts[name];
      if (!layout) reject('INVALID_ARRAY_LAYOUT');
      checkLayout(fields[name], layout);
    }
    if (entry.relation === 'restore_suppression_event') {
      try {
        decodeRestoreSuppressionPhysicalRowV7(entry.row);
      } catch {
        reject();
      }
    }
    const key = currentSourceExtraPhysicalPrimaryKey(entry);
    const relation = currentSourceExtraRelations.indexOf(entry.relation);
    if (
      relation < previousRelation ||
      (relation === previousRelation && key <= previousKey) ||
      seen.has(canonical([entry.relation, key]))
    )
      reject('DUPLICATE_OR_UNORDERED_KEY');
    seen.add(canonical([entry.relation, key]));
    previousRelation = relation;
    previousKey = key;
  }
  if (canonical(result.data) !== canonical(raw)) reject();
  return result.data;
}
