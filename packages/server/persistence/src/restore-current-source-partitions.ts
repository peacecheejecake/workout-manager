function plain(raw: unknown, maximum: number): void {
  let visits = 0,
    bytes = 0;
  const active = new WeakSet<object>();
  function inspect(v: unknown, depth: number): void {
    if (depth > 64 || ++visits > 1000000) reject('PHYSICAL_BYTE_LIMIT');
    bytes += typeof v === 'string' ? Buffer.byteLength(v, 'utf8') : 1;
    if (bytes > maximum) reject('PHYSICAL_BYTE_LIMIT');
    if (
      v === null ||
      typeof v === 'string' ||
      typeof v === 'boolean' ||
      (typeof v === 'number' && Number.isFinite(v))
    )
      return;
    if (
      typeof v !== 'object' ||
      active.has(v) ||
      Object.getOwnPropertySymbols(v).length ||
      (!Array.isArray(v) && Object.getPrototypeOf(v) !== Object.prototype)
    )
      reject();
    if (
      Array.isArray(v) &&
      (Object.keys(v).length !== v.length || Object.getOwnPropertyNames(v).length !== v.length + 1)
    )
      reject();
    active.add(v);
    for (const [key, d] of Object.entries(Object.getOwnPropertyDescriptors(v))) {
      if (Array.isArray(v) && key === 'length') continue;
      if (!d.enumerable || !('value' in d)) reject();
      bytes += Buffer.byteLength(key, 'utf8');
      inspect(d.value, depth + 1);
    }
    active.delete(v);
  }
  inspect(raw, 0);
  if (Buffer.byteLength(JSON.stringify(raw), 'utf8') > maximum) reject('PHYSICAL_BYTE_LIMIT');
}
function canonical(v: unknown): string {
  if (
    v === null ||
    typeof v === 'string' ||
    typeof v === 'boolean' ||
    (typeof v === 'number' && Number.isFinite(v))
  )
    return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.map(canonical).join(',')}]`;
  if (typeof v === 'object')
    return `{${Object.entries(v)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([k, value]) => `${JSON.stringify(k)}:${canonical(value)}`)
      .join(',')}}`;
  return reject();
}
function checkLayout(value: unknown, layout: z.infer<typeof arrayLayout>): void {
  if (layout.isNull) {
    if (value !== null || layout.dimensions.length !== 0) reject('INVALID_ARRAY_LAYOUT');
    return;
  }
  if (!Array.isArray(value)) reject('INVALID_ARRAY_LAYOUT');
  if (layout.dimensions.length === 0) {
    if (value.length !== 0) reject('INVALID_ARRAY_LAYOUT');
    return;
  }
  let cardinality = 1n;
  const widths = layout.dimensions.map((d) => {
    const width = BigInt(d.upperBound) - BigInt(d.lowerBound) + 1n;
    if (width < 1n || width > 5000n) reject('INVALID_ARRAY_LAYOUT');
    cardinality *= width;
    if (cardinality > 5000n) reject('INVALID_ARRAY_LAYOUT');
    return Number(width);
  });
  function dimensions(node: unknown, depth: number): void {
    if (depth === widths.length) {
      if (Array.isArray(node)) reject('INVALID_ARRAY_LAYOUT');
      return;
    }
    if (!Array.isArray(node) || node.length !== widths[depth]) reject('INVALID_ARRAY_LAYOUT');
    for (const child of node) dimensions(child, depth + 1);
  }
  dimensions(value, 0);
}
