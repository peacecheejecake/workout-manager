// Never Number(), Date(), flatten() or other lossy physical coercion.
const float = z.union([
  z
    .number()
    .finite()
    .refine((v) => !Object.is(v, -0)),
  z.enum(['NaN', 'Infinity', '-Infinity', '-0']),
]);
const inet = z
  .string()
  .max(64)
  .refine((v) => {
    const parts = v.split('/');
    if (parts.length > 2) return false;
    const address = parts[0];
    if (!address) return false;
    const version = isIP(address);
    if (!version) return false;
    return (
      parts.length === 1 ||
      (/^(0|[1-9][0-9]*)$/.test(parts[1] ?? '') && Number(parts[1]) <= (version === 4 ? 32 : 128))
    );
  });
