const uuid = z.uuid().transform((value) => value.toLowerCase());
const idempotencyKey = z
  .string()
  .min(8)
  .max(128)
  .regex(/^[A-Za-z0-9._:-]+$/);
const failureCode = z
  .string()
  .min(1)
  .max(100)
  .regex(/^[A-Z0-9_:-]+$/);
const sha256 = z.string().regex(/^[a-f0-9]{64}$/);

const UUID_SEGMENT = '[0-9a-f-]{36}';
/**
 * Object keys are generated by the server and re-derived here before they are recorded.
 * A reference that does not name this tenant, this activity, this track, this upload and
 * the digest of the bytes just validated is refused: persistence never records a key a
 * caller handed it without rebuilding the same key itself.
 */
const FINAL_REF_PATTERN = new RegExp(
  `^private/v1/tenants/(${UUID_SEGMENT})/activities/(${UUID_SEGMENT})/tracks/(${UUID_SEGMENT})/(raw|normalized|map_path)/uploads/(${UUID_SEGMENT})/sha256/([a-f0-9]{64})[.](fit|gpx|json)$`,
);
const finalStorageRef = z.string().max(512).regex(FINAL_REF_PATTERN);

const MAX_ACTIVE_TRACK_UPLOADS = 10;
const MAX_TRACK_UPLOAD_HISTORY = 100;
const MAX_PENDING_TRACK_UPLOAD_BYTES = 128 * 1024 * 1024;
const MAX_LIVE_TRACK_BYTES = 512 * 1024 * 1024;
/**
 * Bytes a tenant may have waiting for reclamation. Deletion schedules cleanup rather than
 * performing it, so without this a loop of store-then-delete would keep passing the live
 * quota while real objects piled up behind a lagging or failing worker.
 */
const MAX_PENDING_CLEANUP_TRACK_BYTES = 512 * 1024 * 1024;
const MAX_TRACK_REVISIONS_PER_ACTIVITY = 20;
const UPLOAD_EXPIRY_MINUTES = 30;
/**
 * How long a prepared upload may keep publishing its three objects. Object cleanup defers
 * while the window is open, so it bounds how long a deletion can wait for a writer; the
 * database CHECK caps it at ten minutes past preparation.
 */
const PUBLICATION_FENCE_SECONDS = 120;

type Reservation = z.infer<typeof activityTrackUploadReservationSchema>;
type ReadResult = z.infer<typeof activityTrackReadResultSchema>;
type ReserveMetadata = z.infer<typeof activityTrackReserveMetadataSchema>;

export class ActivityTrackNotFoundError extends Error {
  readonly code = 'ACTIVITY_TRACK_NOT_FOUND';

  constructor() {
    super('ACTIVITY_TRACK_NOT_FOUND');
    this.name = 'ActivityTrackNotFoundError';
  }
}

export class ActivityTrackUploadStateError extends Error {
  constructor(
    readonly code:
      | 'UPLOAD_FAILED'
      | 'UPLOAD_NOT_PREPARED'
      | 'UPLOAD_NOT_STAGED'
      | 'UPLOAD_QUOTA_EXCEEDED'
      | 'UPLOAD_HISTORY_QUOTA_EXCEEDED'
      | 'TRACK_QUOTA_EXCEEDED'
      | 'TRACK_CLEANUP_BACKLOG_EXCEEDED'
      | 'TRACK_REVISION_LIMIT'
      | 'ACTIVITY_SOURCE_SUPPRESSED',
  ) {
    super(code);
    this.name = 'ActivityTrackUploadStateError';
  }
}

/** Object facts the API produces from bytes it stored itself, never from a client claim. */
