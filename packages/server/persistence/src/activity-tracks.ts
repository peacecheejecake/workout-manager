/**
 * Internal facts of a reservation. They never leave the server as a DTO: the public
 * reservation carries only ids and state, while the parse needs the source revision and
 * the track revision this upload reserved.
 */
export interface ActivityTrackUploadContext {
  readonly uploadId: string;
  readonly activityId: string;
  readonly trackId: string;
  readonly sourceKind: 'fit' | 'fixture' | 'manual';
  readonly sourceId: string;
  readonly sourceRevision: number;
  readonly trackRevision: number;
  readonly recordedTrackIndex: number;
  readonly state: 'reserved' | 'prepared' | 'staged' | 'finalized' | 'failed';
}

export interface ActivityTrackRepository {
  getUpload(athleteId: string, uploadId: string): Promise<Reservation>;
  getUploadContext(athleteId: string, uploadId: string): Promise<ActivityTrackUploadContext>;
  reserve(
    athleteId: string,
    activityId: string,
    metadata: ReserveMetadata,
    requestIdempotencyKey: string,
  ): Promise<Reservation>;
  prepareObjects(
    athleteId: string,
    uploadId: string,
    prepared: PreparedActivityTrackObjects,
  ): Promise<Reservation>;
  markStaged(athleteId: string, uploadId: string): Promise<Reservation>;
  /**
   * True while this upload may still publish: live, prepared or staged, and inside the
   * window preparation granted it. A writer checks this immediately before it makes any
   * object visible.
   */
  publicationFenceOpen(athleteId: string, uploadId: string): Promise<boolean>;
  /**
   * Reclaim the objects of an upload that was cancelled while its writer was publishing.
   * A still-live upload is left alone, so this can never delete a legitimate publication.
   */
  requeueObjects(athleteId: string, uploadId: string): Promise<{ requeued: number }>;
  finalize(athleteId: string, uploadId: string): Promise<ReadResult>;
  fail(athleteId: string, uploadId: string, code: string): Promise<{ failed: true }>;
  read(athleteId: string, activityId: string): Promise<ReadResult>;
  resolveObject(
    athleteId: string,
    activityId: string,
    variant: 'raw' | 'normalized' | 'map_path',
  ): Promise<ActivityTrackObjectRef | null>;
}

