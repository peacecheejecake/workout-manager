import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = new URL('../', import.meta.url);
const spec = JSON.parse(await readFile(new URL('docs/.pre/responsive-spec.json', root), 'utf8'));
const header = '/* Generated by scripts/generate-responsive.mjs. Do not edit directly. */\n';
const { modes, componentContainers, interaction } = spec;
if (
  spec.schemaVersion !== 1 ||
  modes.length !== 3 ||
  modes[0].minInclusive !== 0 ||
  modes.some(
    (mode, index) =>
      !Number.isFinite(mode.minInclusive) ||
      (index < modes.length - 1 && mode.maxExclusive !== modes[index + 1].minInclusive),
  )
) {
  throw new Error('Unsupported or discontinuous responsive specification');
}
const viewportCss = modes
  .map((mode, index) => {
    const rule = `.wm-page { --layout-mode: ${mode.id}; --layout-columns: ${mode.columns}; --page-padding: ${mode.pagePaddingPx}px; --layout-gap: ${mode.gapPx}px; }`;
    return index === 0 ? rule : `@media (min-width: ${mode.minInclusive}px) { ${rule} }`;
  })
  .join('\n');
const css = `${header}
:root { --target-primary: ${interaction.primaryTargetProductGoalPx}px; --target-quick-log: ${interaction.quickLogTargetHeightGoalPx}px; }
.wm-page { box-sizing: border-box; width: 100%; max-width: ${spec.workspaceMaxWidthPx}px; margin-inline: auto; padding: var(--page-padding); padding-bottom: max(var(--page-padding), env(safe-area-inset-bottom)); min-width: 0; }
.wm-grid { display: grid; grid-template-columns: repeat(var(--layout-columns), minmax(0, 1fr)); gap: var(--layout-gap); }
.wm-grid > * { min-width: 0; grid-column: 1 / -1; }
${viewportCss}`;
const moduleCss = `${header}
.container { container: workspace / inline-size; min-width: 0; }
.layout { display: grid; grid-template-columns: minmax(0, 1fr); gap: var(--space-4); min-width: 0; --container-mode: compact; }
.layout > * { min-width: 0; overflow-wrap: anywhere; }
@container workspace (min-width: ${componentContainers.standardMinPx}px) { .layout { --container-mode: standard; gap: var(--space-6); } }
@container workspace (min-width: ${componentContainers.workspaceMinPx}px) { .layout { --container-mode: workspace; } .layout[data-view='split'] { grid-template-columns: minmax(0, 2fr) minmax(0, 1fr); } }
`;
const fixtures = Object.fromEntries(
  spec.testWidthsCssPx.map((width) => [
    `width${width}`,
    {
      name: `${width}px`,
      styles: { width: `${width}px`, height: '900px' },
      type:
        width < modes[1].minInclusive
          ? 'mobile'
          : width < modes[2].minInclusive
            ? 'tablet'
            : 'desktop',
    },
  ]),
);
const ts = `${header}
export const responsiveSpec = ${JSON.stringify(spec)} as const;
export const viewportFixtures = ${JSON.stringify(spec.testWidthsCssPx.map((width) => ({ width, height: 900 })))} as const;
export const fractionalBoundaryWidths = ${JSON.stringify(modes.slice(1).flatMap((mode) => [mode.minInclusive - 0.1, mode.minInclusive]))} as const;
export const storybookViewports = ${JSON.stringify(fixtures)} as const;
export type LayoutMode = (typeof responsiveSpec.modes)[number]['id'];
export function getLayoutMode(width: number): LayoutMode {
  if (!Number.isFinite(width) || width < 0) throw new RangeError('Width must be a finite non-negative CSS pixel value');
  for (const mode of responsiveSpec.modes) { if (mode.maxExclusive === null || width < mode.maxExclusive) return mode.id; }
  throw new RangeError('No layout mode for width');
}
export function getContainerMode(width: number): 'compact' | 'standard' | 'workspace' {
  if (!Number.isFinite(width) || width < 0) throw new RangeError('Width must be a finite non-negative CSS pixel value');
  return width < responsiveSpec.componentContainers.standardMinPx ? 'compact' : width < responsiveSpec.componentContainers.workspaceMinPx ? 'standard' : 'workspace';
}
`;
const outputs = new Map([
  ['responsive.css', css],
  ['adaptive-workspace.module.css', moduleCss],
  ['responsive.ts', ts],
  [
    'tokens.css',
    `${header}${await readFile(new URL('docs/.pre/design-tokens.css', root), 'utf8')}`,
  ],
]);
let drift = false;
for (const [name, source] of outputs) {
  const url = new URL(`packages/ui/foundation/src/${name}`, root);
  const filepath = fileURLToPath(url);
  const formatted = await format(source, { ...(await resolveConfig(filepath)), filepath });
  if (process.argv.includes('--check')) {
    const existing = await readFile(url, 'utf8').catch(() => '');
    if (existing !== formatted) {
      process.stderr.write(`Generated file differs: ${fileURLToPath(url)}\n`);
      drift = true;
    }
  } else {
    await writeFile(url, formatted);
  }
}
if (drift) process.exitCode = 1;
